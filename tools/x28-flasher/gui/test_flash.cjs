// Run: node tools/x28-flasher/gui/test_flash.cjs
const assert = require('node:assert/strict');
const fs = require('node:fs');
const html = fs.readFileSync(`${__dirname}/index.html`, 'utf8');
const source = html.slice(html.indexOf('const leaf ='), html.indexOf('function viewWrite('));
const render = new Function('S', 'esc', 'busy', `${source}; return flashForm();`);
const S = {st: {build: {images: [], backups: ['/backup'], rehearsals: [], stale_rehearsals: 0}}};
const draw = () => render(S, (s) => s, () => false);
assert(draw().includes('data-act="confirm-write" disabled'));
S.flSource = 'backup';
S.flSlot = 'b';
S.flBackupRootfs = 'a';
let view = draw();
assert(!view.includes('data-act="confirm-write" disabled'));
assert(view.includes('id="fl-backup-rootfs"'));
assert(view.includes('name="fl-slot" value="b" checked'));
assert(!view.includes('id="fl-image"'));
assert(!view.includes('id="fl-rehearse"'));
assert(view.includes('not a full-device restore'));
S.flBackup = '/custom-backup';
assert(draw().includes('value="/custom-backup"'));
S.st.build.backups = [];
S.flBackup = '';
assert(draw().includes('placeholder="Folder of your complete verified backup"'));
assert(!draw().includes('data-act="confirm-write" disabled'));
S.flSource = 'image';
S.st.build.images = ['/built'];
view = draw();
assert(view.includes('id="fl-image"'));
assert(view.includes('id="fl-rehearse"'));
assert(!view.includes('id="fl-backup-rootfs"'));
assert(!view.includes('data-act="confirm-write" disabled'));
console.log('flash source selection ok');
